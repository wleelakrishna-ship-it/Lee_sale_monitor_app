/// Looks up [key] in the current language (falling back to English, then the
/// raw key), substituting any `{name}` placeholders from [params].
String tr(BuildContext context, String key, [Map<String, String>? params]) {
  final language = context.watch<LanguageProvider>().language;
  var template = (language == AppLanguage.tamil ? taStrings[key] : enStrings[key]) ??
      enStrings[key] ??
      key;
  if (params != null) {
    for (final entry in params.entries) {
      template = template.replaceAll('{${entry.key}}', entry.value);
    }
  }
  return template;
}
